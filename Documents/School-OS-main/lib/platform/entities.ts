import type { BaseTrackedEntity, BorrowedAssetTracking, DamageBrokenLog } from '../tracking';

export type SchoolEntity = BaseTrackedEntity & { name:string };
export type Organization = SchoolEntity & { schoolYear:string };
export type UserRole = 'Student'|'Teacher'|'Staff'|'Admin'|'HeadOfSchool'|'LabAssistant'|'Librarian'|'TransportStaff';
export type User = SchoolEntity & { email:string; role:UserRole; active:boolean };
export type Student = SchoolEntity & { userId:string; grade:string; homeroomClassId?:string };
export type Teacher = SchoolEntity & { userId:string; departmentId:string; classIds:string[] };
export type Staff = SchoolEntity & { userId:string; departmentId?:string };
export type Admin = Staff;
export type HeadOfSchool = Staff;
export type LabAssistant = Staff;
export type Librarian = Staff;
export type TransportStaff = Staff;
export type Department = SchoolEntity;
export type Class = SchoolEntity & { teacherIds:string[]; studentIds:string[]; departmentId?:string };
export type Asset = SchoolEntity & { assetType:string; location?:string; condition?:string; quantity?:number };
export type LibraryBook = SchoolEntity & { isbn?:string; author:string; copyIds:string[] };
export type BookCopy = Asset & { bookId:string };
export type LabItem = Asset & { lab:'Chemistry'|'Physics'|'Biology'; category:string; unit:string };
export type Assignment = SchoolEntity & { classId:string; teacherId:string; dueAt:string };
export type Submission = BaseTrackedEntity & { assignmentId:string; studentId:string; submittedAt?:string; grade?:string };
export type AttendanceRecord = BaseTrackedEntity & { studentId:string; classId:string; date:string; attendanceStatus:string };
export type StudentRecord = BaseTrackedEntity & { studentId:string; title:string; description:string };
export type DamageRecord = DamageBrokenLog;
export type TransportNotice = BaseTrackedEntity & { studentId:string; date:string; changeType:string };
export type Inquiry = BaseTrackedEntity & { createdBy:string; title:string; threadId:string };
export type CalendarEvent = SchoolEntity & { startsAt:string; endsAt?:string; classId?:string };
export type Project = SchoolEntity & { studentIds:string[]; supervisorId?:string };
export type CASExperience = Project & { strand:'Creativity'|'Activity'|'Service' };
export type BorrowedAsset = BorrowedAssetTracking;
