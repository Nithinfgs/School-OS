export function getEventsForDate(dateStr: string): IBDPCalendarEvent[] {
  return IBDP_ACADEMIC_CALENDAR_EVENTS.filter((e) => {
    return dateStr >= e.startDate && dateStr <= e.endDate;
  });
}

export function getEventsForMonth(year: number, month: number): IBDPCalendarEvent[] {
  const start = year + '-' + String(month).padStart(2, '0') + '-01';
  const lastDay = new Date(year, month, 0).getDate();
  const end = year + '-' + String(month).padStart(2, '0') + '-' + String(lastDay).padStart(2, '0');
  return IBDP_ACADEMIC_CALENDAR_EVENTS.filter((e) => {
    return !(e.endDate < start || e.startDate > end);
  });
}
